/**
 * 1. Mettre à jour l'utilisateur connecté dans la Topbar
 */
function updateCurrentUserDisplay() {
  let user = null;
  const userJson = localStorage.getItem('current_user') || localStorage.getItem('demo_user');
  if (userJson) {
    try {
      user = JSON.parse(userJson);
    } catch (e) {}
  }

  const displayName = user?.username || (user?.email ? user.email.split('@')[0] : 'Admin');
  const userRole = user?.role_name || (user?.is_demo ? 'Mode Démo' : 'Administrateur');

  // Mettre à jour tous les éléments d'affichage utilisateur
  const nameSpans = document.querySelectorAll('.user-info span, #user-display-name');
  nameSpans.forEach(el => {
    el.textContent = displayName;
    el.title = `${displayName} (${userRole})`;
  });

  const avatarImgs = document.querySelectorAll('.user-info img, #user-avatar');
  avatarImgs.forEach(img => {
    img.src = `https://ui-avatars.com/api/?name=${encodeURIComponent(displayName)}&background=1a73e8&color=fff&bold=true`;
    img.alt = displayName;
  });
}

/**
 * 2. Changer de langue et appliquer les traductions
 */
function applyLanguage(lang) {
  if (!translations[lang]) lang = 'fr';
  localStorage.setItem('nexa_lang', lang);

  const t = translations[lang];

  // Gestion RTL pour l'Arabe
  if (lang === 'ar') {
    document.documentElement.setAttribute('dir', 'rtl');
    document.documentElement.setAttribute('lang', 'ar');
  } else {
    document.documentElement.setAttribute('dir', 'ltr');
    document.documentElement.setAttribute('lang', lang);
  }

  // Traduire tous les éléments munis de data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key]) {
      el.textContent = t[key];
    }
  });

  // Traduire les placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (t[key]) {
      el.setAttribute('placeholder', t[key]);
    }
  });

  // Synchroniser la valeur du sélecteur de langue s'il est présent
  const selector = document.getElementById('lang-select');
  if (selector && selector.value !== lang) {
    selector.value = lang;
  }
}

/**
 * 3. Initialiser le Sélecteur de Langue dans la Topbar
 */
function initLanguageSelector() {
  const topbarRight = document.querySelector('.topbar-right');
  if (!topbarRight) return;

  const currentLang = localStorage.getItem('nexa_lang') || 'fr';

  if (!document.getElementById('lang-select')) {
    const langWrapper = document.createElement('div');
    langWrapper.className = 'lang-selector-wrapper';
    langWrapper.style.display = 'inline-flex';
    langWrapper.style.alignItems = 'center';
    langWrapper.style.marginRight = '4px';

    langWrapper.innerHTML = `
      <select id="lang-select" style="background: #f8fafc; border: 1px solid #cbd5e1; border-radius: 6px; padding: 6px 8px; font-size: 13px; font-weight: 600; color: #334155; cursor: pointer; outline: none;">
        <option value="fr" ${currentLang === 'fr' ? 'selected' : ''}>🇫🇷 FR</option>
        <option value="en" ${currentLang === 'en' ? 'selected' : ''}>🇬🇧 EN</option>
        <option value="ar" ${currentLang === 'ar' ? 'selected' : ''}>🇹🇳 AR (عربي)</option>
      </select>
    `;

    // Insérer juste avant les infos utilisateur
    const userInfo = topbarRight.querySelector('.user-info');
    if (userInfo) {
      topbarRight.insertBefore(langWrapper, userInfo);
    } else {
      topbarRight.appendChild(langWrapper);
    }

    const selectEl = document.getElementById('lang-select');
    selectEl.addEventListener('change', (e) => {
      applyLanguage(e.target.value);
    });
  }

  // Appliquer la langue au chargement
  applyLanguage(currentLang);
}

// Lancement automatique dès que le DOM est prêt
document.addEventListener('DOMContentLoaded', () => {
  updateCurrentUserDisplay();
  initLanguageSelector();
});
